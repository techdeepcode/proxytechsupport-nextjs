/**
 * Injects an "Amazon Interview & Career Cluster" section into public/llms.txt and
 * public/llms-full.txt (the AI-agent / LLM discovery manifests) so agentic search
 * bots can find the Amazon cluster's authority pages.
 *
 * Additive + idempotent: the section is wrapped in HTML-comment markers and replaced
 * in place on re-run. Nothing else in the files is touched. Does NOT dump every
 * long-tail location URL — hubs, roles, rounds, LPs and key services are listed;
 * city pages are summarized.
 *
 * Run: node scripts/gen-amazon-llms.mjs
 */
import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const TMP = path.join(ROOT, '.amztmp');
const PUBLIC = path.join(ROOT, 'public');
const START = '<!-- AMAZON-CLUSTER-START (generated by scripts/gen-amazon-llms.mjs) -->';
const END = '<!-- AMAZON-CLUSTER-END -->';

// [compiled module file, exported array name, section heading]
const CATEGORIES = [
  ['core-pages', 'amazonCorePages', 'Hubs & Core Amazon Services (Proxy Interview, Proxy Job, Get Scheduled, Candidate Marketing, Hiring & Interview Process)'],
  ['leadership-principles-pages', 'amazonLeadershipPrinciplesPages', 'Amazon Leadership Principles'],
  ['interview-round-pages', 'amazonRoundPages', 'Amazon Interview Rounds'],
  ['role-info-pages', 'amazonRoleInfoPages', 'Amazon Role Interview Guides'],
  ['role-proxy-interview-pages', 'amazonRoleProxyInterviewPages', 'Amazon Role Proxy Interview Support'],
  ['role-proxy-job-pages', 'amazonRoleProxyJobPages', 'Amazon Role Proxy Job Support'],
  ['technology-pages', 'amazonTechnologyPages', 'Amazon Technology Interview Guides'],
  ['team-pages', 'amazonTeamPages', 'Amazon Team / Business-Unit Interviews'],
  ['country-pages', 'amazonCountryPages', 'Amazon Country Pages'],
  ['city-pages', 'amazonCityPages', 'Amazon City Pages'],
];

function build() {
  fs.rmSync(TMP, { recursive: true, force: true });
  execSync(
    `npx tsc data/amazon/index.ts --outDir .amztmp --module commonjs ` +
      `--moduleResolution node --target es2019 --esModuleInterop --skipLibCheck --resolveJsonModule`,
    { cwd: ROOT, stdio: 'inherit' },
  );
}

function shortTitle(t) {
  return t.split(' — ')[0].split(' | ')[0].split(':')[0].trim();
}

function section() {
  const lines = [START, '', '## Amazon Interview & Career Cluster', ''];
  lines.push(
    'Additive Amazon global authority cluster — Amazon hiring and interview process, role-specific interview guides, interview rounds, Leadership Principles, and the four commercial pillars: Amazon Proxy Interview Support, Get Amazon Interview Scheduled, Amazon Candidate Marketing, and Amazon Proxy Job Support. Informational pages use clean URLs; commercial pages make "proxy" explicit. ProxyTechSupport is independent of Amazon/AWS and does not guarantee interviews or offers. Current through August 2026.',
    '',
  );
  for (const [file, exportName, heading] of CATEGORIES) {
    const mod = require(path.join(TMP, 'amazon', `${file}.js`));
    const pages = mod[exportName] || [];
    if (!pages.length) continue;
    const isCity = file === 'city-pages';
    lines.push(`### ${heading}`);
    // For city pages, only list the informational hiring hubs to avoid dumping every long-tail URL.
    const list = isCity ? pages.filter((p) => p.slug.startsWith('amazon-hiring-')) : pages;
    for (const p of list) {
      const desc = (p.description || '').replace(/\s+/g, ' ').trim();
      lines.push(`- [${shortTitle(p.title)}](/${p.slug}/): ${desc}`);
    }
    lines.push('');
  }
  lines.push(END);
  return lines.join('\n');
}

function inject(fileName, block) {
  const fp = path.join(PUBLIC, fileName);
  if (!fs.existsSync(fp)) {
    console.log(`skip ${fileName} (not present)`);
    return;
  }
  let text = fs.readFileSync(fp, 'utf8');
  const s = text.indexOf(START);
  const e = text.indexOf(END);
  if (s !== -1 && e !== -1 && e > s) {
    text = text.slice(0, s) + block + text.slice(e + END.length);
  } else {
    text = text.replace(/\s*$/, '') + '\n\n' + block + '\n';
  }
  fs.writeFileSync(fp, text, 'utf8');
  console.log(`updated ${fileName}`);
}

build();
const block = section();
inject('llms.txt', block);
inject('llms-full.txt', block);
fs.rmSync(TMP, { recursive: true, force: true });
console.log('Done. Amazon cluster section injected into llms.txt + llms-full.txt.');
