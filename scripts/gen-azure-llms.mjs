/**
 * Injects an "Azure AI / Microsoft Foundry Cluster" section into public/llms.txt and
 * public/llms-full.txt (the AI-agent / LLM discovery manifests) so agentic search
 * bots can find every Azure AI/ML cluster page.
 *
 * Additive + idempotent: the section is wrapped in HTML-comment markers and replaced
 * in place on re-run. Nothing else in the files is touched.
 *
 * Titles + descriptions come directly from the config objects (no build needed).
 * We transpile data/azure to CJS with the local tsc, then require each category
 * array so pages stay grouped by category. Does NOT stuff every long-tail URL —
 * cities are summarized, hubs and key services are listed.
 *
 * Run: node scripts/gen-azure-llms.mjs
 */
import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const TMP = path.join(ROOT, '.aztmp');
const PUBLIC = path.join(ROOT, 'public');
const START = '<!-- AZURE-AIML-CLUSTER-START (generated by scripts/gen-azure-llms.mjs) -->';
const END = '<!-- AZURE-AIML-CLUSTER-END -->';

// [compiled module file, exported array name, section heading]
const CATEGORIES = [
  ['core-pages', 'azureCorePages', 'Hub & Core Azure AI/ML Support'],
  ['foundry-pages', 'azureFoundryPages', 'Microsoft Foundry, Model Router, Foundry IQ & Foundry Local'],
  ['openai-pages', 'azureOpenAiPages', 'Azure OpenAI (Responses API, Realtime, PTU, RAG)'],
  ['agent-pages', 'azureAgentPages', 'Foundry Agent Service & Microsoft Agent Framework'],
  ['search-rag-pages', 'azureSearchRagPages', 'Azure AI Search, Agentic Retrieval, RAG & Vector'],
  ['ml-mlops-pages', 'azureMlMlopsPages', 'Azure Machine Learning, MLOps & LLMOps'],
  ['platform-pages', 'azurePlatformPages', 'Foundry Tools, Databricks, Data, App & AKS'],
  ['ops-pages', 'azureOpsPages', 'Security, Observability, FinOps, DevOps/IaC & Frameworks'],
  ['roles-interview-pages', 'azureRolesInterviewPages', 'Roles, Interview, Profile & Candidate Marketing'],
  ['country-pages', 'azureCountryPages', 'Azure AI/ML Country Pages'],
  ['city-pages', 'azureCityPages', 'Azure AI/ML City Pages'],
  ['industry-pages', 'azureIndustryPages', 'Azure AI Industry Pages'],
  ['kb-pages', 'azureKbPages', 'Azure AI Guides'],
  ['comparison-pages', 'azureComparisonPages', 'Azure AI Comparisons'],
];

function build() {
  fs.rmSync(TMP, { recursive: true, force: true });
  execSync(
    `npx tsc data/azure/index.ts --outDir .aztmp --module commonjs ` +
      `--moduleResolution node --target es2019 --esModuleInterop --skipLibCheck --resolveJsonModule`,
    { cwd: ROOT, stdio: 'inherit' },
  );
}

function shortTitle(t) {
  return t.split(' — ')[0].split(' | ')[0].trim();
}

function section() {
  const lines = [START, '', '## Azure AI / Microsoft Foundry Cluster', ''];
  lines.push(
    'Additive Microsoft Azure AI / ML / Generative AI / Agentic AI cluster — Microsoft Foundry (formerly Azure AI Foundry), Azure OpenAI, Foundry Agent Service, Azure AI Search agentic retrieval, Foundry IQ, Azure Machine Learning, and Azure MLOps. Current through August 2026.',
    '',
  );
  for (const [file, exportName, heading] of CATEGORIES) {
    const mod = require(path.join(TMP, 'azure', `${file}.js`));
    const pages = mod[exportName] || [];
    if (!pages.length) continue;
    lines.push(`### ${heading}`);
    for (const p of pages) {
      const desc = (p.description || '').replace(/\s+/g, ' ').trim();
      lines.push(`- [${shortTitle(p.title)}](/${p.slug}/): ${desc}`);
    }
    lines.push('');
  }
  lines.push(END);
  return lines.join('\n');
}

function inject(fileName, block) {
  const fp = path.join(PUBLIC, fileName);
  let text = fs.readFileSync(fp, 'utf8');
  const s = text.indexOf(START);
  const e = text.indexOf(END);
  if (s !== -1 && e !== -1 && e > s) {
    // Replace the existing marked section (string slice — markers contain regex-special chars).
    text = text.slice(0, s) + block + text.slice(e + END.length);
  } else {
    text = text.replace(/\s*$/, '') + '\n\n' + block + '\n';
  }
  fs.writeFileSync(fp, text, 'utf8');
  console.log(`updated ${fileName}`);
}

build();
const block = section();
inject('llms.txt', block);
inject('llms-full.txt', block);
fs.rmSync(TMP, { recursive: true, force: true });
console.log('Done. Azure AI/ML cluster section injected into llms.txt + llms-full.txt.');
