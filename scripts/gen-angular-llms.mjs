/**
 * Injects an "Angular Job Support Cluster" section into public/llms.txt and
 * public/llms-full.txt (the AI-agent / LLM discovery manifests), so agentic search
 * bots can find every new Angular cluster page.
 *
 * Additive + idempotent: the section is wrapped in HTML-comment markers and replaced
 * in place on re-run. Nothing else in the files is touched.
 *
 * Titles + descriptions are read from the already-built out/<slug>/index.html so the
 * manifest matches exactly what each page renders. Each slug is categorized by its
 * PRIMARY declaration (its own `slug:` / `usCity(` in a batch file), so cross-link
 * references never duplicate or mis-file an entry.
 *
 * Prereq: run `npm run build` first (needs out/*). Then: node scripts/gen-angular-llms.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const ANGULAR_DATA_DIR = path.join(ROOT, 'data', 'angular');
const OUT = path.join(ROOT, 'out');
const START = '<!-- ANGULAR-CLUSTER-START (generated by scripts/gen-angular-llms.mjs) -->';
const END = '<!-- ANGULAR-CLUSTER-END -->';

const CATEGORY_ORDER = [
  ['core-pages', 'Hub & Core Angular Support'],
  ['country-pages', 'Country Angular Job Support Hubs'],
  ['city-usa-pages', 'USA City Angular Job Support Pages'],
  ['city-intl-pages', 'International City Angular Job Support Pages'],
  ['tech-pages', 'Angular Technical Topic Job Support Pages'],
  ['fullstack-pages', 'Angular Full-Stack Combination Pages'],
  ['interview-pages', 'Angular Interview & Get-Interview-Scheduled Pages'],
  ['profile-pages', 'Angular Candidate Marketing & Profile Positioning'],
  ['kb-pages', 'Angular Knowledge Base, Guides & Comparisons'],
];

/** PRIMARY slug declarations only — a page's own slug, not cross-link references. */
function primarySlugsInFile(file) {
  const text = fs.readFileSync(path.join(ANGULAR_DATA_DIR, file + '.ts'), 'utf8');
  const seen = new Set();
  const out = [];
  const add = (s) => { if (!seen.has(s)) { seen.add(s); out.push(s); } };
  for (const m of text.matchAll(/\bslug:\s*'([a-z0-9-]+)'/g)) add(m[1]);
  for (const m of text.matchAll(/usCity\(\s*'([a-z0-9-]+)'/g)) add(m[1]);
  return out;
}

function decode(s) {
  return s
    .replace(/&amp;/g, '&').replace(/&#x27;|&#39;/g, "'").replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#x2F;/g, '/');
}

function metaFor(slug) {
  const file = path.join(OUT, slug, 'index.html');
  if (!fs.existsSync(file)) return null;
  const html = fs.readFileSync(file, 'utf8');
  const t = html.match(/<title>([^<]*)<\/title>/i);
  const d = html.match(/<meta name="description" content="([^"]*)"/i);
  if (!t) return null;
  const title = decode(t[1]).replace(/\s*\|\s*Proxy ?Tech ?Support.*$/i, '').trim();
  const desc = d ? decode(d[1]).trim() : '';
  return { title, desc };
}

let total = 0;
const globalSeen = new Set();
let body = `${START}\n\n## Angular Job Support Cluster\n\n`;
body += '> Real-time Angular job support, production issue help, interview proxy support, and candidate marketing for Angular developers — central hub plus country, city, technical-topic, full-stack, interview, profile-marketing, and knowledge-base pages. Covers modern Angular: standalone components, signals, RxJS, NgRx, Angular Material, SSR/hydration, micro-frontends, and full-stack combinations. Entry point: [Angular Support Services](/angular-support-services/).\n\n';

for (const [file, heading] of CATEGORY_ORDER) {
  const lines = [];
  for (const slug of primarySlugsInFile(file)) {
    if (globalSeen.has(slug)) continue;
    const meta = metaFor(slug);
    if (!meta) continue;
    globalSeen.add(slug);
    lines.push(`- [${meta.title}](/${slug}/): ${meta.desc}`);
    total++;
  }
  if (lines.length) body += `### ${heading}\n\n${lines.join('\n')}\n\n`;
}
body += `${END}\n`;

function inject(fileName) {
  const p = path.join(ROOT, 'public', fileName);
  let text = fs.readFileSync(p, 'utf8');
  if (text.includes(START) && text.includes(END)) {
    text = text.replace(new RegExp(`${START}[\\s\\S]*?${END}\\n?`), body);
  } else {
    text = text.replace(/\s*$/, '\n') + '\n' + body;
  }
  fs.writeFileSync(p, text, 'utf8');
  // Mirror into out/ so the current export reflects the change without a rebuild.
  const op = path.join(OUT, fileName);
  if (fs.existsSync(op)) fs.writeFileSync(op, text, 'utf8');
  console.log(`updated ${fileName} (+${total} Angular cluster entries)`);
}

inject('llms.txt');
inject('llms-full.txt');
console.log('Done.');
