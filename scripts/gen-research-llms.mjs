const groupIndex = (entries) =>
  entries.map((e) => `- [${e.title}](${e.path}): ${e.short}`).join('\n');
const groupFull = (entries) =>
  entries.map((e) => `- [${e.title}](${e.path}): ${e.full}`).join('\n');

function buildSection(full) {
  const pubText = full ? groupFull(PUBS) : groupIndex(PUBS);
  const hubText = full ? HUB.full : HUB.short;
  return [
    START,
    '',
    '## ProxyTech Research — Autonomous AI Agent Security',
    '',
    'An independent engineering-research cluster analyzing autonomous AI agent security from live evidence: 2024–2026 arXiv papers and primary security disclosures. Individual publications use flat URLs; /research/ is the discovery archive. This is an independent analysis that references academic work — it is not peer-reviewed and is not affiliated with arXiv or any university.',
    '',
    '### Research Archive',
    `- [${HUB.title}](${HUB.path}): ${hubText}`,
    '',
    '### Research Publications (flat URLs)',
    pubText,
    '',
    '### Blog Lead-ins',
    full ? groupFull(BLOGS) : groupIndex(BLOGS),
    '',
    END,
  ].join('\n');
}

function inject(file, full) {
  const p = path.join(PUBLIC, file);
  if (!fs.existsSync(p)) {
    console.error(`! missing ${file} — skipped`);
    return;
  }
  let text = fs.readFileSync(p, 'utf8');
  const section = buildSection(full);
  const si = text.indexOf(START);
  const ei = text.indexOf(END);
  if (si !== -1 && ei !== -1) {
    text = text.slice(0, si) + section + text.slice(ei + END.length);
  } else {
    text = text.replace(/\s*$/, '') + '\n\n' + section + '\n';
  }
  fs.writeFileSync(p, text, 'utf8');
  console.log(`✓ ${file}: research cluster section (${PUBS.length} pubs + hub) ${si !== -1 ? 'replaced' : 'appended'}`);
}

inject('llms.txt', false);
inject('llms-full.txt', true);
console.log('Done.');
