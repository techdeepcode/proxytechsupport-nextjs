/**
 * Injects an "AWS AI/ML & Generative AI Cluster" section into public/llms.txt and
 * public/llms-full.txt (the AI-agent / LLM discovery manifests), so agentic search
 * bots can find every AWS AI/ML cluster page.
 *
 * Additive + idempotent: the section is wrapped in HTML-comment markers and replaced
 * in place on re-run. Nothing else in the files is touched.
 *
 * Titles + descriptions are read from the already-built out/<slug>/index.html so the
 * manifest matches exactly what each page renders. Categories come from which
 * data/aws/<file>.ts a slug is declared in.
 *
 * Prereq: run `npm run build` first (needs out/*). Then: node scripts/gen-aws-llms.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const AWS_DATA_DIR = path.join(ROOT, 'data', 'aws');
const OUT = path.join(ROOT, 'out');
const START = '<!-- AWS-AIML-CLUSTER-START (generated by scripts/gen-aws-llms.mjs) -->';
const END = '<!-- AWS-AIML-CLUSTER-END -->';

const CATEGORY_ORDER = [
  ['core-pages', 'Hub & Core AWS AI/ML Support'],
  ['bedrock-pages', 'Amazon Bedrock Pages'],
  ['agentcore-pages', 'Amazon Bedrock AgentCore Pages'],
  ['sagemaker-pages', 'Amazon SageMaker Platform Pages'],
  ['sagemaker-ai-pages', 'Amazon SageMaker AI Pages'],
  ['nova-pages', 'Amazon Nova Pages'],
  ['mlops-pages', 'AWS MLOps & GenAIOps Pages'],
  ['data-vector-pages', 'AWS AI Data & Vector Pages'],
  ['purpose-built-pages', 'AWS Purpose-Built AI Service Pages'],
  ['infra-pages', 'AWS AI Infrastructure & Container Pages'],
  ['security-observability-pages', 'AWS AI Security, Governance & Observability Pages'],
  ['integration-frameworks-pages', 'AWS AI Application & Agent Framework Pages'],
  ['role-pages', 'AWS AI/ML Role & Interview Pages'],
  ['country-pages', 'AWS AI/ML Country Pages'],
  ['city-usa-pages', 'USA AWS AI/ML City Pages'],
  ['city-intl-pages', 'International AWS AI/ML City Pages'],
  ['industry-pages', 'Industry AWS AI Pages'],
  ['kb-pages', 'AWS AI/ML Knowledge Base Guides'],
  ['comparison-pages', 'AWS AI/ML Comparison Pages'],
];

function slugsInFile(file) {
  const text = fs.readFileSync(path.join(AWS_DATA_DIR, file + '.ts'), 'utf8');
  const seen = new Set();
  const out = [];
  for (const m of text.matchAll(/slug:\s*'([a-z0-9]+(?:-[a-z0-9]+){2,})'/g)) {
    if (!seen.has(m[1])) { seen.add(m[1]); out.push(m[1]); }
  }
  return out;
}

function decode(s) {
  return s
    .replace(/&amp;/g, '&').replace(/&#x27;|&#39;/g, "'").replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#x2F;/g, '/');
}

function metaFor(slug) {
  const file = path.join(OUT, slug, 'index.html');
  if (!fs.existsSync(file)) return null;
  const html = fs.readFileSync(file, 'utf8');
  const t = html.match(/<title>([^<]*)<\/title>/i);
  const d = html.match(/<meta name="description" content="([^"]*)"/i);
  if (!t) return null;
  let title = decode(t[1]).replace(/\s*\|\s*Proxy ?Tech ?Support.*$/i, '').trim();
  const desc = d ? decode(d[1]).trim() : '';
  return { title, desc };
}

const declared = new Set();
for (const [file] of CATEGORY_ORDER) for (const s of slugsInFile(file)) declared.add(s);

let total = 0;
let body = `${START}\n\n## AWS AI/ML & Generative AI Cluster\n\n`;
body += '> Real-time AWS AI/ML job support, production help, interview proxy support, and candidate marketing for Amazon Bedrock, Bedrock AgentCore, Amazon Nova, Amazon SageMaker AI, RAG, and AWS MLOps professionals — technical content current through August 2026. Entry point: [AWS AI/ML Job Support](/aws-ai-ml-job-support/).\n\n';

for (const [file, heading] of CATEGORY_ORDER) {
  const slugs = slugsInFile(file).filter((s) => declared.has(s));
  const lines = [];
  for (const slug of slugs) {
    const meta = metaFor(slug);
    if (!meta) continue;
    lines.push(`- [${meta.title}](/${slug}/): ${meta.desc}`);
    total++;
  }
  if (lines.length) body += `### ${heading}\n\n${lines.join('\n')}\n\n`;
}
body += `${END}\n`;

function inject(fileName) {
  const p = path.join(ROOT, 'public', fileName);
  let text = fs.readFileSync(p, 'utf8');
  if (text.includes(START) && text.includes(END)) {
    text = text.replace(new RegExp(`${START}[\\s\\S]*?${END}\\n?`), body);
  } else {
    text = text.replace(/\s*$/, '\n') + '\n' + body;
  }
  fs.writeFileSync(p, text, 'utf8');
  const op = path.join(OUT, fileName);
  if (fs.existsSync(op)) fs.writeFileSync(op, text, 'utf8');
  console.log(`updated ${fileName} (+${total} AWS AI/ML cluster entries)`);
}

inject('llms.txt');
inject('llms-full.txt');
console.log('Done.');
