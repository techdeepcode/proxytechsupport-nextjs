/**
 * Injects a "Hugging Face / Generative AI / LLM Engineering Cluster" section into
 * public/llms.txt and public/llms-full.txt (the AI-agent / LLM discovery manifests)
 * so agentic search bots can find every Hugging Face cluster page.
 *
 * Additive + idempotent: the section is wrapped in HTML-comment markers and replaced
 * in place on re-run. Nothing else in the files is touched.
 *
 * Titles + descriptions come directly from the config objects (no build needed).
 * We transpile data/huggingface to CJS with the local tsc, then require each category
 * array so pages stay grouped by category. Categories that do not exist yet are
 * skipped, so the script works while the cluster is still being built out.
 *
 * Run: node scripts/gen-huggingface-llms.mjs
 */
import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const TMP = path.join(ROOT, '.hftmp');
const PUBLIC = path.join(ROOT, 'public');
const START = '<!-- HUGGINGFACE-CLUSTER-START (generated by scripts/gen-huggingface-llms.mjs) -->';
const END = '<!-- HUGGINGFACE-CLUSTER-END -->';

// [compiled module file, exported array name, section heading]
const CATEGORIES = [
  ['core-pages', 'huggingFaceCorePages', 'Hub & Core Hugging Face Support'],
  ['platform-pages', 'huggingFacePlatformPages', 'Hub, CLI, Inference Endpoints, Providers, Spaces & Gradio'],
  ['transformers-pages', 'huggingFaceTransformersPages', 'Transformers — Training, Inference, Quantization, Multimodal'],
  ['finetuning-pages', 'huggingFaceFineTuningPages', 'Fine-Tuning — PEFT, LoRA, QLoRA, TRL, Alignment, Accelerate'],
  ['agents-pages', 'huggingFaceAgentsPages', 'Agents & Agentic RL — smolagents, MCP, OpenEnv'],
  ['embeddings-pages', 'huggingFaceEmbeddingsPages', 'Embeddings, RAG, Reranking, Sentence Transformers & TEI'],
  ['inference-pages', 'huggingFaceInferencePages', 'LLM Serving — TGI, vLLM, Local Inference'],
  ['performance-pages', 'huggingFacePerformancePages', 'Performance — Quantization, Optimum, Kernels, GPU'],
  ['diffusers-pages', 'huggingFaceDiffusersPages', 'Generative Media — Diffusers, Text-to-Image'],
  ['mlops-pages', 'huggingFaceMlopsPages', 'Data, MLOps & Evaluation — Datasets, Tokenizers, Trackio, Lighteval'],
  ['cloud-pages', 'huggingFaceCloudPages', 'Cloud — Hugging Face on AWS, Azure, GCP'],
  ['interview-pages', 'huggingFaceInterviewPages', 'Hugging Face & LLM Proxy Interview Support'],
  ['comparison-pages', 'huggingFaceComparisonPages', 'Hugging Face Guides & Comparisons'],
  ['country-pages', 'huggingFaceCountryPages', 'Hugging Face Country Pages'],
];

function build() {
  fs.rmSync(TMP, { recursive: true, force: true });
  execSync(
    `npx tsc data/huggingface/index.ts --outDir .hftmp --module commonjs ` +
      `--moduleResolution node --target es2019 --esModuleInterop --skipLibCheck --resolveJsonModule`,
    { cwd: ROOT, stdio: 'inherit' },
  );
}

function shortTitle(t) {
  return t.split(' — ')[0].split(' | ')[0].trim();
}

function section() {
  const lines = [START, '', '## Hugging Face / Generative AI / LLM Engineering Cluster', ''];
  lines.push(
    'Additive Hugging Face / Generative AI / LLM Engineering cluster — Transformers, PEFT/LoRA/QLoRA, TRL (SFT/DPO/GRPO), Sentence Transformers, RAG, Diffusers, smolagents, OpenEnv, Inference Endpoints, Inference Providers, TGI/TEI/vLLM, Optimum, Kernels, Trackio, and Lighteval. Current through September 2026.',
    '',
  );
  for (const [file, exportName, heading] of CATEGORIES) {
    let mod;
    try {
      mod = require(path.join(TMP, 'huggingface', `${file}.js`));
    } catch {
      continue; // category not built yet
    }
    const pages = mod[exportName] || [];
    if (!pages.length) continue;
    lines.push(`### ${heading}`);
    for (const p of pages) {
      const desc = (p.description || '').replace(/\s+/g, ' ').trim();
      lines.push(`- [${shortTitle(p.title)}](/${p.slug}/): ${desc}`);
    }
    lines.push('');
  }
  lines.push(END);
  return lines.join('\n');
}

function inject(fileName, block) {
  const fp = path.join(PUBLIC, fileName);
  let text = fs.readFileSync(fp, 'utf8');
  const s = text.indexOf(START);
  const e = text.indexOf(END);
  if (s !== -1 && e !== -1 && e > s) {
    text = text.slice(0, s) + block + text.slice(e + END.length);
  } else {
    text = text.replace(/\s*$/, '') + '\n\n' + block + '\n';
  }
  fs.writeFileSync(fp, text, 'utf8');
  console.log(`updated ${fileName}`);
}

build();
const block = section();
inject('llms.txt', block);
inject('llms-full.txt', block);
fs.rmSync(TMP, { recursive: true, force: true });
console.log('Done. Hugging Face cluster section injected into llms.txt + llms-full.txt.');
