/**
 * Injects a "Kubernetes + Agentic AI + AI Infrastructure Cluster" section into
 * public/llms.txt and public/llms-full.txt (the AI-agent / LLM discovery manifests),
 * so agentic search bots can find every Kubernetes AI cluster page.
 *
 * Additive + idempotent: the section is wrapped in HTML-comment markers and replaced
 * in place on re-run. Nothing else in the files is touched.
 *
 * Titles + descriptions are read from the already-built out/<slug>/index.html so the
 * manifest matches exactly what each page renders. Categories come from which
 * data/kubernetes/<file>.ts a slug is declared in.
 *
 * Prereq: run `npm run build` first (needs out/*). Then: node scripts/gen-kubernetes-llms.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const K8S_DATA_DIR = path.join(ROOT, 'data', 'kubernetes');
const OUT = path.join(ROOT, 'out');
const START = '<!-- KUBERNETES-AI-CLUSTER-START (generated by scripts/gen-kubernetes-llms.mjs) -->';
const END = '<!-- KUBERNETES-AI-CLUSTER-END -->';

const CATEGORY_ORDER = [
  ['core-pages', 'Hub & Core Kubernetes AI Support'],
  ['agentic-pages', 'Agentic AI Infrastructure Pages'],
  ['mcp-pages', 'MCP (Model Context Protocol) Pages'],
  ['inference-pages', 'LLM Inference, GPU & Scheduling Pages'],
  ['cloud-pages', 'Cloud Kubernetes AI Pages (EKS / AKS / GKE)'],
  ['onprem-pages', 'OpenShift, On-Premises, Private & Sovereign AI Pages'],
  ['incident-pages', 'Production Incident & Troubleshooting Pages'],
  ['industry-pages', 'Industry Kubernetes AI Pages'],
  ['usecase-pages', 'Use-Case Architecture Pages'],
  ['country-pages', 'Country & Regional Kubernetes AI Pages'],
  ['city-pages', 'City-Level Kubernetes AI Pages'],
  ['role-pages', 'Role & Career Kubernetes AI Pages'],
  ['incident-postmortem-pages', 'Real Security Incident & CVE Postmortems'],
];

function slugsInFile(file) {
  const text = fs.readFileSync(path.join(K8S_DATA_DIR, file + '.ts'), 'utf8');
  const seen = new Set();
  const out = [];
  for (const m of text.matchAll(/slug:\s*'([a-z0-9]+(?:-[a-z0-9]+){2,})'/g)) {
    if (!seen.has(m[1])) { seen.add(m[1]); out.push(m[1]); }
  }
  return out;
}

function decode(s) {
  return s
    .replace(/&amp;/g, '&').replace(/&#x27;|&#39;/g, "'").replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#x2F;/g, '/');
}

function metaFor(slug) {
  const file = path.join(OUT, slug, 'index.html');
  if (!fs.existsSync(file)) return null;
  const html = fs.readFileSync(file, 'utf8');
  const t = html.match(/<title>([^<]*)<\/title>/i);
  const d = html.match(/<meta name="description" content="([^"]*)"/i);
  if (!t) return null;
  const title = decode(t[1]).replace(/\s*\|\s*Proxy ?Tech ?Support.*$/i, '').trim();
  const desc = d ? decode(d[1]).trim() : '';
  return { title, desc };
}

const declared = new Set();
for (const [file] of CATEGORY_ORDER) for (const s of slugsInFile(file)) declared.add(s);

let total = 0;
let body = `${START}\n\n## Kubernetes + Agentic AI + AI Infrastructure Cluster\n\n`;
body += '> Real-time job support, production incident help, and interview support for operating production AI and autonomous agents on Kubernetes — agentic AI, LLM inference (vLLM, KServe, NVIDIA Dynamo), GPU scheduling (DRA, gang scheduling), MCP, AI SRE, AI security, and AI FinOps across Amazon EKS, Azure AKS, Google GKE, Red Hat OpenShift, and on-prem/bare-metal. Technical content current through September/October 2026 (Kubernetes v1.37). Entry point: [Kubernetes AI Job Support](/kubernetes-ai-job-support/).\n\n';

for (const [file, heading] of CATEGORY_ORDER) {
  const slugs = slugsInFile(file).filter((s) => declared.has(s));
  const lines = [];
  for (const slug of slugs) {
    const meta = metaFor(slug);
    if (!meta) continue;
    lines.push(`- [${meta.title}](/${slug}/): ${meta.desc}`);
    total++;
  }
  if (lines.length) body += `### ${heading}\n\n${lines.join('\n')}\n\n`;
}
body += `${END}\n`;

function inject(fileName) {
  const p = path.join(ROOT, 'public', fileName);
  let text = fs.readFileSync(p, 'utf8');
  if (text.includes(START) && text.includes(END)) {
    text = text.replace(new RegExp(`${START}[\\s\\S]*?${END}\\n?`), body);
  } else {
    text = text.replace(/\s*$/, '\n') + '\n' + body;
  }
  fs.writeFileSync(p, text, 'utf8');
  const op = path.join(OUT, fileName);
  if (fs.existsSync(op)) fs.writeFileSync(op, text, 'utf8');
  console.log(`updated ${fileName} (+${total} Kubernetes AI cluster entries)`);
}

inject('llms.txt');
inject('llms-full.txt');
console.log('Done.');
