/**
 * Injects a "Global AI/ML Job Support Cluster" section into public/llms.txt and
 * public/llms-full.txt (the AI-agent / LLM discovery manifests), so agentic search
 * bots can find every new AI/ML cluster page.
 *
 * Additive + idempotent: the section is wrapped in HTML-comment markers and replaced
 * in place on re-run. Nothing else in the files is touched.
 *
 * Titles + descriptions are read from the already-built out/<slug>/index.html so the
 * manifest matches exactly what each page renders. Categories come from which
 * data/aiml/<file>.ts a slug is declared in.
 *
 * Prereq: run `npm run build` first (needs out/*). Then: node scripts/gen-aiml-llms.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const AIML_DATA_DIR = path.join(ROOT, 'data', 'aiml');
const OUT = path.join(ROOT, 'out');
const START = '<!-- AIML-CLUSTER-START (generated by scripts/gen-aiml-llms.mjs) -->';
const END = '<!-- AIML-CLUSTER-END -->';

const CATEGORY_ORDER = [
  ['core-pages', 'Hub & Core AI/ML Support'],
  ['country-pages', 'Country AI/ML Job Support Hubs'],
  ['city-usa-pages', 'USA City AI/ML Job Support Pages'],
  ['city-intl-pages', 'International City AI/ML Job Support Pages'],
  ['tech-pages', 'AI/ML Technology Job Support Pages'],
  ['role-pages', 'AI/ML Role Job Support Pages'],
  ['interview-pages', 'AI/ML Interview Proxy Support Pages'],
  ['scheduled-pages', 'Get AI/ML Interview Scheduled Pages'],
  ['candidate-marketing-pages', 'AI/ML Candidate Marketing & Profile Positioning'],
  ['industry-pages', 'Industry AI/ML Job Support Pages'],
  ['kb-pages', 'AI/ML Knowledge Base Guides'],
  ['comparison-pages', 'AI/ML Comparison & Problem-Solution Pages'],
];

function slugsInFile(file) {
  const text = fs.readFileSync(path.join(AIML_DATA_DIR, file + '.ts'), 'utf8');
  const seen = new Set();
  const out = [];
  for (const m of text.matchAll(/'([a-z0-9]+(?:-[a-z0-9]+){2,})'/g)) {
    if (!seen.has(m[1])) { seen.add(m[1]); out.push(m[1]); }
  }
  return out;
}

function decode(s) {
  return s
    .replace(/&amp;/g, '&').replace(/&#x27;|&#39;/g, "'").replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#x2F;/g, '/');
}

function metaFor(slug) {
  const file = path.join(OUT, slug, 'index.html');
  if (!fs.existsSync(file)) return null;
  const html = fs.readFileSync(file, 'utf8');
  const t = html.match(/<title>([^<]*)<\/title>/i);
  const d = html.match(/<meta name="description" content="([^"]*)"/i);
  if (!t) return null;
  let title = decode(t[1]).replace(/\s*\|\s*Proxy ?Tech ?Support.*$/i, '').trim();
  const desc = d ? decode(d[1]).trim() : '';
  return { title, desc };
}

// Only slugs that actually belong to the cluster (declared in a batch file) AND were built.
const declared = new Set();
for (const [file] of CATEGORY_ORDER) for (const s of slugsInFile(file)) declared.add(s);

let total = 0;
let body = `${START}\n\n## Global AI/ML Job Support Cluster\n\n`;
body += '> Real-time AI/ML job support, production issue help, interview proxy support, and candidate marketing for AI, GenAI, LLM, RAG, MLOps, and data science professionals — global hub plus country, city, technology, role, interview, and industry pages. Entry point: [Global AI/ML Job Support](/global-ai-ml-job-support/).\n\n';

for (const [file, heading] of CATEGORY_ORDER) {
  const slugs = slugsInFile(file).filter((s) => declared.has(s));
  const lines = [];
  for (const slug of slugs) {
    const meta = metaFor(slug);
    if (!meta) continue;
    lines.push(`- [${meta.title}](/${slug}/): ${meta.desc}`);
    total++;
  }
  if (lines.length) body += `### ${heading}\n\n${lines.join('\n')}\n\n`;
}
body += `${END}\n`;

function inject(fileName) {
  const p = path.join(ROOT, 'public', fileName);
  let text = fs.readFileSync(p, 'utf8');
  if (text.includes(START) && text.includes(END)) {
    text = text.replace(new RegExp(`${START}[\\s\\S]*?${END}\\n?`), body);
  } else {
    text = text.replace(/\s*$/, '\n') + '\n' + body;
  }
  fs.writeFileSync(p, text, 'utf8');
  // Mirror into out/ so the current export reflects the change without a rebuild.
  const op = path.join(OUT, fileName);
  if (fs.existsSync(op)) fs.writeFileSync(op, text, 'utf8');
  console.log(`updated ${fileName} (+${total} AI/ML cluster entries)`);
}

inject('llms.txt');
inject('llms-full.txt');
console.log('Done.');
